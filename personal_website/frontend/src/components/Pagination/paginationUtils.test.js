import { getPageUrl, calculatePageRange } from './paginationUtils';

/**
 * Набор тестов для утилит пагинации
 *
 * Содержит тесты для функций, используемых в компоненте пагинации:
 * - getPageUrl: формирование URL для перехода на конкретную страницу
 * - calculatePageRange: вычисление диапазона страниц для отображения
 */
describe('paginationUtils', () => {
  /**
   * Тесты для функции getPageUrl
   *
   * Проверяет корректность формирования URL с параметром страницы
   * в различных сценариях:
   * - когда URL не содержит параметров
   * - когда URL уже содержит параметры
   */
  describe('getPageUrl', () => {
    /**
     * Проверяет добавление параметра page к URL без существующих параметров.
     *
     * При отсутствии параметров в URL, параметр page добавляется через символ '?'.
     */
    test('добавляет параметр page к URL без параметров', () => {
      const baseUrl = '/blog/';
      const pageNumber = 3;
      const expected = '/blog/?page=3';
      expect(getPageUrl(baseUrl, pageNumber)).toBe(expected);
    });

    /**
     * Проверяет добавление параметра page к URL с существующими параметрами.
     *
     * При наличии параметров в URL, параметр page добавляется через символ '&'.
     */
    test('добавляет параметр page к URL с существующими параметрами', () => {
      const baseUrl = '/blog/?category=tech';
      const pageNumber = 2;
      const expected = '/blog/?category=tech&page=2';
      expect(getPageUrl(baseUrl, pageNumber)).toBe(expected);
    });
  });

  /**
   * Тесты для функции calculatePageRange
   *
   * Проверяет корректность вычисления диапазона страниц для отображения
   * в различных сценариях:
   * - для первой страницы
   * - для средней страницы
   * - для последней страницы
   * - когда общее количество страниц меньше максимального отображаемого
   */
  describe('calculatePageRange', () => {
    /**
     * Проверяет вычисление диапазона для первой страницы.
     *
     * Для первой страницы диапазон начинается с 1 и учитывает максимальное
     * количество отображаемых страниц.
     */
    test('вычисляет диапазон для первой страницы', () => {
      const result = calculatePageRange(1, 10);
      expect(result.startPage).toBe(1);
      expect(result.endPage).toBe(5);
    });

    /**
     * Проверяет вычисление диапазона для средней страницы.
     *
     * Для средней страницы диапазон центрируется относительно текущей страницы.
     */
    test('вычисляет диапазон для средней страницы', () => {
      const result = calculatePageRange(5, 10);
      expect(result.startPage).toBe(3);
      expect(result.endPage).toBe(7);
    });

    /**
     * Проверяет вычисление диапазона для последней страницы.
     *
     * Для последней страницы диапазон корректно ограничивается
     * общим количеством страниц.
     */
    test('вычисляет диапазон для последней страницы', () => {
      const result = calculatePageRange(10, 10);
      expect(result.startPage).toBe(6);
      expect(result.endPage).toBe(10);
    });

    /**
     * Проверяет обработку количества страниц меньше максимального.
     *
     * Когда общее количество страниц меньше максимального отображаемого,
     * диапазон корректно ограничивается.
     */
    test('корректно обрабатывает количество страниц меньше максимального', () => {
      const result = calculatePageRange(3, 3);
      expect(result.startPage).toBe(1);
      expect(result.endPage).toBe(3);
    });
  });
});
