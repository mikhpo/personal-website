#!/bin/bash
#
# Скрипт для перезапуска компонентов systemd-развертывания.
# Перезапускает приложение (personal-website.service) и nginx.
# База данных управляется отдельно от сервера приложения
# и здесь не перезапускается.

mode="simple"

#######################################
# Выводит подсказку по бизнес-логике скрипта.
#######################################
function help() {
    echo
    echo "Скрипт для перезапуска сервисов сервера: приложения и nginx."
    echo "Опции:"
    echo "-h    Показать подсказки по скрипту"
    echo "-f    Режим полного перезапуска: daemon-reload и проверка конфигурации nginx"
    echo
}

#######################################
# Перезапуск приложения.
# В случае полного перезапуска предварительно выполняется daemon-reload
# (актуализация юнитов после изменения файлов в /etc/systemd/system).
# Глобальная переменная:
#    mode - режим перезапуска
#######################################
function restart_application() {
    if [[ "${mode}" == "full" ]]; then
        echo "Обновление конфигурации systemd"
        sudo systemctl daemon-reload
    fi
    echo "Перезапуск приложения"
    sudo systemctl restart personal-website.service
}

#######################################
# Перезапуск nginx.
# В случае полного перезапуска производится тестирование конфигурации:
# необходимо, если изменялась конфигурация nginx (vhost проекта).
# Глобальная переменная:
#    mode - режим перезапуска
#######################################
function restart_nginx() {
    if [[ "${mode}" == "full" ]]; then
        echo "Перезапуск nginx с тестированием конфигурации"
        sudo nginx -t
    else
        echo "Перезапуск nginx"
    fi
    sudo systemctl restart nginx
}

#######################################
# Проверка на наличие опциональных аргументов, переданных скрипту.
#######################################
function get_options() {
    while getopts "hf" option; do
        case $option in
        h)
            help
            exit
            ;;
        f)
            mode="full"
            ;;
        *)
            echo "Ошибка: некорректный аргумент"
            exit
            ;;
        esac
    done
}

#######################################
# Основное тело скрипта.
#######################################
function main() {
    get_options
    restart_application
    restart_nginx
}

# Вызов основного потока скрипта.
main "$@"
